"""
Guardrails module — enforces AI ethics, safety rules, and HAM tone
for the Nutrition Agentic AI application.
"""

import re

# ─── Blocked topic patterns ────────────────────────────────────────────────────
HARMFUL_PATTERNS = [
    r"\bsuicide\b", r"\bself[- ]harm\b", r"\bstarv(e|ation)\b",
    r"\banorexia\b", r"\bbulimia\b", r"\boverdo(se|sing)\b",
    r"\bkill (myself|yourself)\b", r"\bextreme fast(ing)?\b",
    r"\bcrash diet\b", r"\bpurge\b", r"\blaxative abuse\b",
]

MEDICAL_PRESCRIPTION_PATTERNS = [
    r"\bprescri(be|ption)\b", r"\bdosage of\b", r"\btake \d+ mg\b",
    r"\bdiagnos(e|is)\b", r"\btreat(ment)? for\b",
]

DISCLAIMER = (
    "\n\n---\n"
    "⚕️ **Medical Disclaimer:** This nutrition plan is generated by an AI "
    "assistant for informational and general wellness purposes only. "
    "It is **not** a substitute for professional medical advice, diagnosis, "
    "or treatment. Always consult a qualified healthcare provider or "
    "registered dietitian before making significant changes to your diet, "
    "especially if you have a medical condition. Never disregard professional "
    "medical advice because of something you have read here."
)


def contains_harmful_content(text: str) -> bool:
    """Return True if the input contains potentially harmful patterns."""
    lowered = text.lower()
    for pattern in HARMFUL_PATTERNS:
        if re.search(pattern, lowered):
            return True
    return False


def contains_prescription_request(text: str) -> bool:
    """Return True if the user is asking for medical prescriptions/diagnoses."""
    lowered = text.lower()
    for pattern in MEDICAL_PRESCRIPTION_PATTERNS:
        if re.search(pattern, lowered):
            return True
    return False


def validate_age(age) -> tuple[bool, str]:
    """Validate age is within a reasonable range."""
    try:
        age = int(age)
        if age < 1 or age > 120:
            return False, "Age must be between 1 and 120."
        return True, ""
    except (ValueError, TypeError):
        return False, "Age must be a valid number."


def sanitize_input(text: str) -> str:
    """Strip leading/trailing whitespace and limit length."""
    if not isinstance(text, str):
        text = str(text)
    return text.strip()[:2000]


def get_harmful_response() -> str:
    return (
        "I'm here to support your health and wellbeing in a safe, positive way. "
        "The topic you mentioned is outside the scope of what I can assist with here. "
        "If you are struggling, please reach out to a healthcare professional or a "
        "helpline in your area. I'm happy to help you with nutrition and wellness advice."
    )


def get_prescription_response() -> str:
    return (
        "I appreciate your trust, but I'm not able to prescribe medications, "
        "provide dosages, or diagnose medical conditions — that requires a "
        "licensed healthcare professional. I *can* help you understand general "
        "nutrition principles and healthy eating habits. Would you like that?"
    )


def append_disclaimer(text: str) -> str:
    """Append the standard medical disclaimer to any nutrition plan."""
    return text + DISCLAIMER
